"""Generate js/data/strokes.js from Unicode Unihan.zip.

Kangxi-style stroke count (used by 姓名學) = full-form radical strokes + residual strokes
from kRSUnicode, so 氵=水(4), 艹=艸(6), 阝(left)=阜(8), 阝(right)=邑(7), 王=玉(5) ...
"""
import zipfile, re, json, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
z = zipfile.ZipFile(pathlib.Path(__file__).with_name('Unihan.zip'))

def rad_strokes(r):
    bounds = [(6,1),(29,2),(60,3),(94,4),(117,5),(146,6),(166,7),(175,8),(186,9),
              (194,10),(200,11),(204,12),(208,13),(210,14),(211,15),(213,16),(214,17)]
    for hi, s in bounds:
        if r <= hi: return s

rs, total, trad, big5 = {}, {}, {}, set()
for l in z.read('Unihan_OtherMappings.txt').decode('utf8').splitlines():
    if '	kBigFive	' in l: big5.add(int(l.split('	')[0][2:], 16))
for l in z.read('Unihan_IRGSources.txt').decode('utf8').splitlines():
    if not l.startswith('U+'): continue
    cp, key, val = l.split('\t')
    c = int(cp[2:], 16)
    if key == 'kRSUnicode': rs[c] = val.split()[0]
    elif key == 'kTotalStrokes': total[c] = int(val.split()[-1])
for l in z.read('Unihan_Variants.txt').decode('utf8').splitlines():
    if not l.startswith('U+'): continue
    cp, key, val = l.split('\t')
    if key == 'kTraditionalVariant':
        c = int(cp[2:], 16)
        vs = [int(v[2:].split('<')[0], 16) for v in val.split()]
        others = [v for v in vs if v != c]
        # keep chars that are themselves valid traditional (Big5) chars, e.g. 干 后 余 于 范
        if others and not (c in vs and c in big5): trad[c] = others[0]

NUM = {'一':1,'二':2,'三':3,'四':4,'五':5,'六':6,'七':7,'八':8,'九':9,'十':10}
START, END = 0x3400, 0x9FFF
arr = []
for c in range(START, END + 1):
    v = 0
    if c in rs:
        m = re.match(r"(\d+)('*)\.(-?\d+)", rs[c])
        rad, simp, res = int(m.group(1)), m.group(2), int(m.group(3))
        v = rad_strokes(rad) + res if not simp else total.get(c, 0)
    ch = chr(c)
    if ch in NUM: v = NUM[ch]
    arr.append(v)

s2t = ''.join(chr(k) + chr(v) for k, v in sorted(trad.items()) if k < 0x10000 and v < 0x10000)
out = ROOT / 'js' / 'data' / 'strokes.js'
out.write_text(
    '// Generated by build/gen_strokes.py from Unicode Unihan (kRSUnicode / kTraditionalVariant).\n'
    f'window.STROKE_DATA = {{ start: {START}, kangxi: [{",".join(map(str, arr))}],\n'
    f'  s2t: {json.dumps(s2t, ensure_ascii=False)} }};\n', encoding='utf8')
print(out, out.stat().st_size, len(trad))
